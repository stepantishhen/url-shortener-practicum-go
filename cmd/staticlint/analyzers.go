// analyzers contains the complete analyzer suite used by staticlint.
// The Staticcheck SA and ST analyzers are unwrapped to their go/analysis API.
var analyzers = buildAnalyzers()

func buildAnalyzers() []*analysis.Analyzer {
	result := []*analysis.Analyzer{
		appends.Analyzer,
		asmdecl.Analyzer,
		assign.Analyzer,
		atomic.Analyzer,
		bools.Analyzer,
		buildtag.Analyzer,
		cgocall.Analyzer,
		composite.Analyzer,
		copylock.Analyzer,
		defers.Analyzer,
		directive.Analyzer,
		errorsas.Analyzer,
		framepointer.Analyzer,
		hostport.Analyzer,
		httpresponse.Analyzer,
		ifaceassert.Analyzer,
		loopclosure.Analyzer,
		lostcancel.Analyzer,
		nilfunc.Analyzer,
		printf.Analyzer,
		shadow.Analyzer,
		shift.Analyzer,
		sigchanyzer.Analyzer,
		slog.Analyzer,
		stdmethods.Analyzer,
		stdversion.Analyzer,
		stringintconv.Analyzer,
		structtag.Analyzer,
		testinggoroutine.Analyzer,
		tests.Analyzer,
		timeformat.Analyzer,
		unmarshal.Analyzer,
		unreachable.Analyzer,
		unsafeptr.Analyzer,
		unusedresult.Analyzer,
		waitgroup.Analyzer,
		osExitAnalyzer,
		nilerr.Analyzer,
		forcetypeassert.Analyzer,
	}

	for _, analyzer := range staticcheck.Analyzers {
		if strings.HasPrefix(analyzer.Analyzer.Name, "SA") {
			result = append(result, analyzer.Analyzer)
		}
	}
	for _, analyzer := range stylecheck.Analyzers {
		if strings.HasPrefix(analyzer.Analyzer.Name, "ST") {
			result = append(result, analyzer.Analyzer)
		}
	}
	return result
}
